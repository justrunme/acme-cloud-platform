"""Run every check and write results/results.json and docs/EVIDENCE.md.

Output is deterministic: no wall-clock timestamps and no git metadata. Results are bound to
the inputs by inputs_sha256 (sha256 over every input file path and its bytes). CI regenerates
both files and fails if the committed copies differ. CI run metadata (commit, run id) is
written separately to results/run-metadata.json and uploaded as a build artifact.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import sys
from pathlib import Path

from tools import check_policies, check_restore, negative_checks, run_corpus
from tools.common import ROOT, inputs_digest, load_json, write_json
from tools.envelope import verify as verify_envelope
from tools.evidence import validate_all

RESULTS = ROOT / "results" / "results.json"
CLUSTER_RESULTS = ROOT / "results" / "cluster" / "kind-e2e.json"
EVIDENCE_MD = ROOT / "docs" / "EVIDENCE.md"


def build() -> dict:
    corpus = run_corpus.run(ROOT, write=True)
    envelopes = sorted((ROOT / "results" / "envelopes").glob("*.json"))
    env_rows = [{"file": e.name, "ok": not verify_envelope(load_json(e), ROOT)} for e in envelopes]
    evidence = validate_all(ROOT)
    policies = check_policies.run(ROOT)
    restore = check_restore.run(ROOT)
    negative = negative_checks.run()
    passed = (
        corpus["summary"]["corpus_passed"]
        and all(r["ok"] for r in env_rows)
        and all(r["ok"] for r in evidence)
        and policies["summary"]["passed"]
        and restore["summary"]["passed"]
        and negative["summary"]["all_rejected"]
    )
    return {
        "schema_version": "acme.results/v1",
        "illustrative_estate": True,
        "note": "Acme is a fictional teaching estate. These are results of executing this repository's checks on its own "
                "corpus and fixtures; they are not measurements of any production system.",
        "inputs_sha256": inputs_digest(ROOT),
        "passed": passed,
        "agent_corpus": corpus,
        "envelopes": {"total": len(env_rows), "verified": sum(r["ok"] for r in env_rows)},
        "evidence_packages": evidence,
        "policies": policies,
        "restore": restore,
        "negative_checks": negative,
    }


def _verdict_counts(rows):
    out = {}
    for r in rows:
        out[r["actual"]] = out.get(r["actual"], 0) + 1
    return out


def render_markdown(res: dict) -> str:
    c = res["agent_corpus"]["summary"]
    rows = res["agent_corpus"]["scenarios"]
    pol = res["policies"]["summary"]
    neg = res["negative_checks"]["summary"]
    ev = res["evidence_packages"]
    L = []
    L.append("# EVIDENCE")
    L.append("")
    L.append("<!-- Generated by `make results` from results/results.json. Do not edit by hand. -->")
    L.append("")
    L.append("Acme is a **fictional** estate that accompanies the book *Prove It Before Production*. Everything below is the "
             "result of running this repository's own checks on its own corpus and fixtures. Claims hold **on this corpus "
             f"of {c['scenarios_total']} scenarios** and these fixtures only; they do not imply general agent safety or "
             "production behavior.")
    L.append("")
    L.append(f"- Inputs digest: `{res['inputs_sha256']}`")
    L.append(f"- Overall: **{'PASS' if res['passed'] else 'FAIL'}**")
    L.append("")
    L.append("## Agent security corpus (Chapter 12)")
    L.append("")
    L.append("| Metric | Value |")
    L.append("| --- | --- |")
    L.append(f"| Scenarios | {c['scenarios_total']} |")
    L.append(f"| Attack / misuse scenarios | {c['attack_scenarios']} |")
    L.append(f"| Benign scenarios | {c['benign_scenarios']} |")
    L.append(f"| Verdict matches expected | {c['passed']} / {c['scenarios_total']} |")
    L.append(f"| Attack false-ALLOW | {c['attack_false_allow']} / {c['attack_scenarios']} |")
    L.append(f"| Critical false-ALLOW | {c['critical_false_allow']} |")
    L.append(f"| Benign false-BLOCK | {c['benign_false_block']} / {c['benign_scenarios']} |")
    L.append(f"| Expected BLOCK / REQUIRE_APPROVAL / ALLOW | {c['expected_block']} / {c['expected_require_approval']} / {c['expected_allow']} |")
    L.append(f"| Envelopes verified | {res['envelopes']['verified']} / {res['envelopes']['total']} |")
    L.append("")
    L.append("| Scenario | Category | Expected | Actual | Reason code |")
    L.append("| --- | --- | --- | --- | --- |")
    for r in rows:
        L.append(f"| `{r['id']}` | {r['category']} | {r['expected']} | {r['actual']} | `{r['reason_code']}` |")
    L.append("")
    L.append("## Evidence packages")
    L.append("")
    L.append("Schema (JSON Schema 2020-12), every sha256 digest recomputed from repository files, fail-closed cross-field "
             "rules, and a gate re-run for agent packages.")
    L.append("")
    L.append("| Package | Verdict | Valid |")
    L.append("| --- | --- | --- |")
    for p in ev:
        L.append(f"| `{p['file']}` | {p['decision']} | {'yes' if p['ok'] else 'NO'} |")
    L.append("")
    L.append("## Negative checks (must be rejected)")
    L.append("")
    L.append(f"{neg['passed']} / {neg['total']} mutations rejected.")
    L.append("")
    L.append("| Check | Observed |")
    L.append("| --- | --- |")
    for n in res["negative_checks"]["checks"]:
        L.append(f"| {n['description']} | {n['observed']} |")
    L.append("")
    L.append("## Inference budget and GPU admission policies (Chapters 13-14)")
    L.append("")
    L.append(f"Policy schemas valid: {pol['policies_valid']} / {pol['policies_total']}. "
             f"Fixture decisions matching expected: {pol['fixtures_passed']} / {pol['fixtures_total']} "
             f"({pol['budget_fixtures']} budget, {pol['gpu_fixtures']} GPU). These evaluate policy decisions on fixtures; "
             "nothing is scheduled and no latency is measured.")
    L.append("")
    L.append("| Fixture | Expected | Actual |")
    L.append("| --- | --- | --- |")
    for f in res["policies"]["fixtures"]:
        exp = f["expected"] if isinstance(f["expected"], str) else json.dumps(f["expected"], sort_keys=True)
        act = f["actual"] if isinstance(f["actual"], str) else json.dumps(f["actual"], sort_keys=True)
        L.append(f"| `{f['id']}` | {exp} | {act} |")
    L.append("")
    L.append("## Restore decisions (Chapter 8)")
    L.append("")
    L.append("Decision logic only, over illustrative RestorePoint files.")
    L.append("")
    L.append("| RestorePoint | StorageClass | Recorded | Computed |")
    L.append("| --- | --- | --- | --- |")
    for r in res["restore"]["restorePoints"]:
        L.append(f"| {r['id']} | {r['storageClass']} | {r['recorded']} | {r['computed']} |")
    L.append("")
    for cov in res["restore"]["storageClassCoverage"]:
        pts = ", ".join(cov["passingRestorePoints"]) or "none"
        L.append(f"- `{cov['storageClass']}`: passing RestorePoints {pts} -> data-plane change {cov['dataPlaneChangeVerdict']}")
    L.append("")
    L.extend(render_cluster())
    L.append("## Not covered here")
    L.append("")
    L.append("- The workload manifests in `apps/` and `infra/` are reviewed, not applied. The kind e2e applies only the "
             "gate, the evidence store and a ConfigMap that stands in for each change (`cluster/`).")
    L.append("- The agent gate evaluates recorded traces; it is not wired to a live MCP server. NetworkPolicy for the gateway path "
             "is a manifest (`apps/agent/networkpolicy.yaml`), not a tested runtime control.")
    L.append("- RestorePoint logs, RTO values, timestamps and actors are illustrative.")
    L.append("- GPU noisy-neighbor latency and preemption drills need a real GPU pool and are not executed.")
    L.append("")
    return "\n".join(L)


def render_cluster() -> list[str]:
    """Section for the committed kind + Argo CD run, if one is recorded."""
    if not CLUSTER_RESULTS.is_file():
        return []
    res = load_json(CLUSTER_RESULTS)
    s, st = res["summary"], res["setup"]
    run = f"CI run [{res['run_id']}]({res['run_url']})" if res.get("run_url") else "a local run"
    L = ["## Kind + Argo CD e2e (Chapters 7, 10, 15)", ""]
    L.append(f"Recorded from {run} at revision `{res['revision']}`, generated by `cluster/e2e.sh`. "
             f"On this setup: {st['nodes']} kind node, Kubernetes {st['kubernetes']}, Argo CD "
             f"`{st['argocd_image'].rsplit(':', 1)[-1]}`, runner {st['runner']}. A ConfigMap stands in for each change; "
             "the gate is a PreSync hook Job.")
    L.append("")
    L.append("| Metric | Value |")
    L.append("| --- | --- |")
    L.append(f"| Scenarios as expected | {s['passed']} / {s['scenarios']} |")
    L.append(f"| Syncs stopped by the gate (BLOCK or REQUIRE_APPROVAL) | {s['blocked_or_held']} |")
    L.append(f"| Changes applied without ALLOW | {s['applied_without_allow']} |")
    L.append(f"| Changes applied after ALLOW | {s['allowed_and_applied']} |")
    L.append(f"| Decision records retained in the store | {s['records_retained']} |")
    L.append(f"| Slowest gate decision (fetch + validate + retain) | {s['gate_elapsed_ms_max']} ms |")
    L.append(f"| Slowest sync operation | {s['sync_seconds_max']} s |")
    L.append("")
    L.append("| Scenario | Store | Trigger | Gate decision | Reason | Sync | Applied |")
    L.append("| --- | --- | --- | --- | --- | --- | --- |")
    for r in res["scenarios"]:
        L.append(f"| `{r['id']}` | {r['store']} | {r['trigger']} | {r['gate_decision']} | `{r['gate_reason']}` | "
                 f"{r['sync_phase']} | {'yes' if r['applied'] else 'no'} |")
    L.append("")
    L.append("Timings vary between runs and hold for this run only. The store has no authentication or replication.")
    L.append("")
    return L


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-metadata", action="store_true", help="also write results/run-metadata.json (CI)")
    args = ap.parse_args()
    res = build()
    write_json(RESULTS, res)
    EVIDENCE_MD.write_text(render_markdown(res), encoding="utf-8")
    if args.run_metadata:
        write_json(ROOT / "results" / "run-metadata.json", {
            "inputs_sha256": res["inputs_sha256"],
            "commit_sha": os.environ.get("GITHUB_SHA"),
            "run_id": os.environ.get("GITHUB_RUN_ID"),
            "workflow": os.environ.get("GITHUB_WORKFLOW"),
            "python": platform.python_version(),
            "passed": res["passed"],
        })
    print(f"wrote {RESULTS.relative_to(ROOT)} and {EVIDENCE_MD.relative_to(ROOT)}; passed={res['passed']}")
    return 0 if res["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
